const roots: string[] = [];

function tempRoot() {
  const root = fs.mkdtempSync(
    path.join(os.tmpdir(), 'vellira-production-contract-parity-')
  );
  roots.push(root);
  return root;
}

function plan(
  root: string,
  overrides: Partial<ComponentGeneratorOptions> = {}
): ComponentGenerationPlan {
  return createComponentGenerationPlan({
    root,
    options: {
      componentName: 'ContractProbe',
      platform: 'both',
      layer: 'components',
      category: 'utility',
      profile: 'base',
      capabilities: [],
      parts: [],
      force: false,
      ...overrides,
    },
  });
}

async function writeCanonicalPlanArtifacts(plan: ComponentGenerationPlan) {
  const platforms = plan.targets.map((target) => target.packageName);
  const metadata = await formatGeneratedContent(
    plan.metadataFile,
    renderMetadataTemplate({
      componentName: plan.componentName,
      layer: plan.layer,
      category: plan.category,
      platforms,
      profile: plan.profile,
      capabilities: resolvePlanCapabilities(plan),
      typeOwnership: plan.typeOwnership,
      dependencies: plan.dependencies,
      icons: plan.icons,
      tokens: plan.tokens,
      assets: plan.assets,
      componentTokens: plan.componentTokens,
    })
  );

  fs.mkdirSync(path.dirname(plan.metadataFile), { recursive: true });
  fs.writeFileSync(plan.metadataFile, metadata);

  const metadataName = `${plan.componentName[0].toLowerCase()}${plan.componentName.slice(1)}Metadata`;
  fs.writeFileSync(
    plan.metadataBarrelFile,
    `import { ${metadataName} } from './${plan.componentName}.metadata';\n\nexport const componentMetadata = [\n  ${metadataName},\n] as const;\n`
  );

  const docsContract = await formatGeneratedContent(
    plan.docsContractFile,
    renderComponentDocsContract(plan)
  );
  fs.mkdirSync(path.dirname(plan.docsContractFile), { recursive: true });
  fs.writeFileSync(plan.docsContractFile, docsContract);

  const docsVariable = getComponentDocsContractVariable(plan.componentName);
  fs.writeFileSync(
    plan.docsContractRegistryFile,
    `import { ${docsVariable} } from './${plan.componentName}.docs';\n\nexport const componentDocsContracts = [${docsVariable}] as const;\n`
  );

  for (const target of getComponentDocsTargets(plan)) {
    fs.mkdirSync(path.dirname(target.docsFile), { recursive: true });
    fs.writeFileSync(
      target.docsFile,
      '<!-- Generated by scripts/generators/component-docs/generate-component-docs.ts -->\n'
    );
  }
}

function snapshotFiles(directory: string): Map<string, Buffer> {
  if (!fs.existsSync(directory)) {
    return new Map();
  }

  const files = new Map<string, Buffer>();

  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      for (const [filePath, contents] of snapshotFiles(entryPath)) {
        files.set(filePath, contents);
      }
    } else if (entry.isFile()) {
      files.set(entryPath, fs.readFileSync(entryPath));
    }
  }

  return files;
}

function changedFiles(
  before: Map<string, Buffer>,
  after: Map<string, Buffer>
): { createdFiles: string[]; updatedFiles: string[] } {
  return {
    createdFiles: [...after.keys()]
      .filter((filePath) => !before.has(filePath))
      .sort(),
    updatedFiles: [...after.keys()]
      .filter((filePath) => {
        const previous = before.get(filePath);
        const current = after.get(filePath);

        return (
          previous !== undefined &&
          current !== undefined &&
          !previous.equals(current)
        );
      })
      .sort(),
  };
}

